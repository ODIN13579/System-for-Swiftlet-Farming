
-- B3-12: private snapshots and idempotent AI predator events.
-- Do not modify V1-V6.

CREATE TABLE swiftletcare.ai_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id BIGINT NOT NULL
        REFERENCES swiftletcare.devices(id) ON DELETE RESTRICT,
    media_type VARCHAR(16) NOT NULL
        CHECK (media_type IN ('image/jpeg', 'image/png')),
    image_bytes BYTEA NOT NULL,
    byte_size INTEGER NOT NULL
        CHECK (byte_size BETWEEN 1 AND 307200),
    sha256 CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
        DEFAULT clock_timestamp(),
    CONSTRAINT ck_ai_snapshot_size
        CHECK (octet_length(image_bytes) = byte_size)
);

CREATE INDEX idx_ai_snapshots_camera_created
    ON swiftletcare.ai_snapshots(camera_id, created_at DESC);

ALTER TABLE swiftletcare.anomaly_events
    ADD COLUMN event_id VARCHAR(150),
    ADD COLUMN snapshot_id BIGINT
        REFERENCES swiftletcare.ai_snapshots(id)
        ON DELETE RESTRICT;

-- PostgreSQL allows multiple NULL values in a UNIQUE column,
-- preserving compatibility with old anomaly_events rows.
ALTER TABLE swiftletcare.anomaly_events
    ADD CONSTRAINT uq_anomaly_events_event_id UNIQUE(event_id);

ALTER TABLE swiftletcare.alerts
    ADD COLUMN snapshot_id BIGINT
        REFERENCES swiftletcare.ai_snapshots(id)
        ON DELETE RESTRICT;

CREATE INDEX idx_anomaly_snapshot
    ON swiftletcare.anomaly_events(snapshot_id)
    WHERE snapshot_id IS NOT NULL;

CREATE INDEX idx_alert_snapshot
    ON swiftletcare.alerts(snapshot_id)
    WHERE snapshot_id IS NOT NULL;
